"""
Layer 5: AI Investigation Agent - evidence minimiser.

Builds the ONLY data the LLM ever sees: a numbered list of evidence items (E1, E2, ...) taken
from what PayGuard has STORED for the case (the transaction's risk evaluation, the wallet-cluster
finding, and any step-up escalation). Every item's text is generated by PayGuard itself, never
copied from client free-text fields.

Data minimisation: no sender/recipient IDs, names, emails, device IDs, PayPal order IDs or wallet
addresses are included (not even pseudonymised; the model does not need them). Wallet findings
are described by pattern, time window and transfer count. Amount and currency are included
because the red flags depend on them.
"""

from typing import Any, Dict, List, Optional


def _short(text: str, limit: int = 300) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= limit else text[: limit - 1] + "…"


def build_case_evidence(tx: Dict[str, Any], cluster_finding: Optional[Dict[str, Any]] = None,
                        escalation_reason: Optional[str] = None) -> Dict[str, Any]:
    """
    tx: the stored transaction record (db.get_transaction).
    cluster_finding: the stored ClusterFinding dict for the case (or None).
    escalation_reason: e.g. why step-up verification failed.
    """
    items: List[Dict[str, str]] = []

    def add(category: str, text: str) -> None:
        items.append({"id": f"E{len(items) + 1}", "category": category, "text": _short(text)})

    if escalation_reason:
        add("step_up_escalation", f"Step-up verification failed: {escalation_reason}.")

    if cluster_finding:
        n = len(cluster_finding.get("evidence_transfers") or [])
        window = ""
        if cluster_finding.get("time_window_start") and cluster_finding.get("time_window_end"):
            window = (f" Evidence: {n} PYUSD transfers between {cluster_finding['time_window_start']} and "
                      f"{cluster_finding['time_window_end']}.")
        prov = ", ".join(cluster_finding.get("provenance") or []) or "unknown"
        add("wallet_cluster", f"{cluster_finding.get('details', '')}{window} Data provenance: {prov}.")

    for f in sorted(tx.get("contributing_factors") or [], key=lambda x: -abs(x.get("impact", 0))):
        if str(f.get("factor", "")).startswith("Blockchain") and cluster_finding:
            continue  # already covered by the wallet_cluster item
        add("rule_factor", f"{f.get('factor')} (+{f.get('impact'):g} risk points): {f.get('description')}")

    b = tx.get("score_breakdown") or {}
    exps = tx.get("model_explanations") or []
    if b.get("model_probability") is not None:
        top = "; ".join(f"{e['label']} = {e['value']} ({e['direction']})" for e in exps[:3])
        add("ml_model", f"Fraud model (XGBoost trained on PaySim simulated data) probability "
                        f"{b['model_probability']:.1%}, contributing {b.get('model_points', 0):g} risk points. "
                        f"Top SHAP drivers: {top}.")

    for o in tx.get("policy_overrides") or []:
        add("policy_override", o)

    case = {
        "risk_score": tx.get("risk_score"),
        "risk_band": tx.get("risk_band"),
        "required_action": tx.get("action"),
        "amount": tx.get("amount"),
        "currency": tx.get("currency", "USD"),
    }
    return {"case": case, "evidence": items, "categories": sorted({i["category"] for i in items})}
